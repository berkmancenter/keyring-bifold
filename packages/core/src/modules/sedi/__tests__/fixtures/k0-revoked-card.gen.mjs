#!/usr/bin/env node
/**
 * Writes sedi/guardian/k0RevokedTestCard.ts: the K0 kit's revoked Guardian card ("G-revoked", Jordan as the guardian
 * of Sam), carried WITH its revocation (its status log's issued and revoked events, and the revoked-state proof), so a
 * phone holding it shows that the card says it was revoked. Deterministic: the same fixtures always give the same file.
 * k0TestCard.test.ts fails if the written file drifts from the fixtures.
 *
 * Usage, from packages/core: node src/modules/sedi/__tests__/fixtures/k0-revoked-card.gen.mjs
 * Then run prettier on the written file.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const FX = join(here, 'k0-utah-v2')
const OUT = join(here, '..', '..', 'guardian', 'k0RevokedTestCard.ts')
const text = (f) => readFileSync(join(FX, f), 'utf8')
const prov = JSON.parse(text('PROVENANCE.json'))
const tel = (stem, states) => ({
  ripText: text(`tel-${stem}-rip.json`),
  updateTexts: states.map((s) => text(`tel-${stem}-${s}.json`)),
})

const card = {
  guardianSaid: prov.creds['G-revoked'].said,
  holder: prov.aids.jordan,
  kels: ['roy', 'deb', 'sue', 'jordan'].map((k) => text(`kel-${k}.cesr`)),
  tels: [tel('unit', ['issued']), tel('agent', ['issued']), tel('G-revoked', ['issued', 'revoked'])],
  creds: [
    text('acdc-unit-issued-proofed.cesr'),
    text('acdc-agent-issued-proofed.cesr'),
    text('acdc-G-revoked-revoked-proofed.cesr'),
  ],
}

const header = `/**
 * The K0 kit's revoked Guardian card ("G-revoked", Jordan as the guardian of Sam), WITH its revocation: the status log
 * carries the issued and the revoked events, and the credential its revoked-state proof. The card the Developer action
 * "Hold the revoked test card (K0)" puts on an approver's phone, so a tester build can show a revoked card being
 * refused on the person's phone ("The card shows it was revoked"). A test card from the keripy kit
 * (sedi/__tests__/fixtures/k0-utah-v2), copied here because a build does not ship the test fixtures; k0TestCard.test.ts
 * fails if it drifts from them.
 *
 * Generated by sedi/__tests__/fixtures/k0-revoked-card.gen.mjs; do not edit by hand.
 *
 * @module sedi/guardian/k0RevokedTestCard
 */

/** The card: the revoked Guardian credential, the holder it names, and the chain to the K0 test root. */
export const K0_REVOKED_TEST_GUARDIAN_CARD: {
  guardianSaid: string
  holder: string
  kels: string[]
  tels: { ripText: string; updateTexts: string[] }[]
  creds: string[]
} = `

writeFileSync(OUT, header + JSON.stringify(card, null, 2) + '\n')
console.log(`wrote ${OUT}`)
