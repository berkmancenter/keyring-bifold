// Generates src/modules/sedi/guardian/k0RevokedOmittedCard.ts from the K0 kit's fixtures: the card the Developer action
// "Hold the revoked card without its revocation (K0)" puts on an approver's phone. It is the K0 "G-revoked" Guardian card
// with its revocation LEFT OUT: the status log cut to its inception and issuance, the issued-state proof, and the issuing
// agent's (Sue's) key history cut before the event that anchors the revocation. Checked against its own copy alone it
// reads as issued (the known "as shown by the holder" bound); checked against Sue's PUBLISHED history (a live did:webs
// fetch) it is refused, because that history anchors the revocation. Deterministic: the same fixtures give the same file.
//
// Run from packages/core:  node src/modules/sedi/__tests__/fixtures/k0-revoked-omitted-card.gen.mjs
// then prettier --write the output. k0RevokedOmittedCard.test.ts fails if the file drifts from the fixtures.
/* eslint-disable no-console -- a run-once generator, run with node */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const fx = (f) => fs.readFileSync(path.join(here, 'k0-utah-v2', f), 'utf8')
const prov = JSON.parse(fx('PROVENANCE.json'))

/** Sue's stream cut before the event that anchors G-revoked's revocation (the same cut as guardianK0's sueCut). */
export function sueCut() {
  const t = fx('kel-sue.cesr')
  const rev = JSON.parse(fx('tel-G-revoked-revoked.json')).d
  const at = t.lastIndexOf('{"v":"', t.indexOf(rev))
  if (at <= 0) throw new Error('fixture: the revocation seal is not in kel-sue.cesr')
  return t.slice(0, at)
}

const tel = (stem) => ({ ripText: fx(`tel-${stem}-rip.json`), updateTexts: [fx(`tel-${stem}-issued.json`)] })
const card = {
  guardianSaid: prov.creds['G-revoked'].said,
  holder: prov.aids.jordan,
  kels: [fx('kel-roy.cesr'), fx('kel-deb.cesr'), sueCut(), fx('kel-jordan.cesr')],
  tels: [tel('unit'), tel('agent'), tel('G-revoked')],
  creds: [
    fx('acdc-unit-issued-proofed.cesr'),
    fx('acdc-agent-issued-proofed.cesr'),
    fx('acdc-G-revoked-issued-proofed.cesr'),
  ],
}

const out = path.join(here, '..', '..', 'guardian', 'k0RevokedOmittedCard.ts')
const body = `/**
 * The K0 kit's revoked Guardian card ("G-revoked", Jordan as the guardian of Sam) with its revocation LEFT OUT: the card
 * the Developer action "Hold the revoked card without its revocation (K0)" puts on an approver's phone, for the demo of a
 * revocation caught from the state's published record. Its status log stops at issuance, its proof is the issued-state
 * one, and the issuing agent's (Sue's) key history is cut before the event that anchors the revocation, so the card's
 * own copy reads as issued. Only a live fetch of Sue's published history (demo roots with a Demo state host) shows the
 * revocation. A test card, copied from sedi/__tests__/fixtures/k0-utah-v2 because a build does not ship the fixtures;
 * k0RevokedOmittedCard.test.ts fails if it drifts from them.
 *
 * Generated by sedi/__tests__/fixtures/k0-revoked-omitted-card.gen.mjs; do not edit by hand.
 *
 * @module sedi/guardian/k0RevokedOmittedCard
 */

/** The card: the Guardian credential, the holder it names, and the chain to the K0 test root. */
export const K0_REVOKED_OMITTED_CARD: {
  guardianSaid: string
  holder: string
  kels: string[]
  tels: { ripText: string; updateTexts: string[] }[]
  creds: string[]
} = ${JSON.stringify(card, null, 2)}
`
fs.writeFileSync(out, body)
console.log(out, Buffer.byteLength(JSON.stringify(card)), 'bytes')
