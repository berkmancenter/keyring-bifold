// Bundle the trust-tasks-tf schemas Keyring checks vetting documents against
// into self-contained JSON Schemas (every cross-file $ref inlined under $defs,
// annotations dropped) and write them as a TypeScript module.
//
//   node scripts/bundle-vetting-schemas.mjs <trust-tasks-tf>/specs <commit> \
//     > packages/core/src/modules/trust-tasks/module/vettingSchemas.ts
//   npx prettier --write packages/core/src/modules/trust-tasks/module/vettingSchemas.ts
import fs from 'node:fs'
import path from 'node:path'

const specs = path.resolve(process.argv[2])
const cache = new Map()
const load = (file) => {
  if (!cache.has(file)) cache.set(file, JSON.parse(fs.readFileSync(file, 'utf8')))
  return cache.get(file)
}
const pointer = (doc, frag) =>
  frag
    .replace(/^\//, '')
    .split('/')
    .filter(Boolean)
    .reduce((o, k) => o[k.replace(/~1/g, '/').replace(/~0/g, '~')], doc)

function bundle(entryFile, entryFrag) {
  const defs = {}
  const keys = new Map() // file#frag -> def key
  const keyFor = (file, frag) => {
    const id = `${file}#${frag}`
    if (keys.has(id)) return keys.get(id)
    const base = frag.split('/').pop()
    let key = base
    for (let i = 2; Object.values(Object.fromEntries(keys)).includes(key); i++) key = `${base}${i}`
    keys.set(id, key)
    defs[key] = rewrite(pointer(load(file), frag), file)
    return key
  }
  const rewrite = (node, file, parentKey) => {
    if (Array.isArray(node)) return node.map((n) => rewrite(n, file))
    if (!node || typeof node !== 'object') return node
    const out = {}
    for (const [k, v] of Object.entries(node)) {
      if (k === '$id' || k === '$anchor' || k === '$schema' || k === '$comment') continue
      // Annotations only; a member named like one under `properties` is kept.
      if ((k === 'description' || k === 'title' || k === 'examples') && parentKey !== 'properties') continue
      if (k === '$defs' && file === entryFile && node === pointer(load(entryFile), entryFrag)) continue
      if (k === '$ref' && typeof v === 'string') {
        const [rel, frag = ''] = v.split('#')
        const target = rel ? path.resolve(path.dirname(file), rel) : file
        out.$ref = `#/$defs/${keyFor(target, frag)}`
        continue
      }
      out[k] = rewrite(v, file, k)
    }
    return out
  }
  const root = rewrite(pointer(load(entryFile), entryFrag), entryFile)
  return { ...root, $defs: defs }
}

const at = (p) => path.join(specs, p)
const out = {
  vettingSessionPayload: bundle(at('vetting/session/0.1/payload.schema.json'), ''),
  vettingCard: bundle(at('vetting/_shared/0.1/vetting-card.schema.json'), '/$defs/VettingCard'),
  vettingRequirements: bundle(at('vtc/join-requests/manifest/0.2/payload.schema.json'), '/$defs/VettingRequirements'),
  vetterProfilePayload: bundle(at('vtc/vetting/vetters/profile/0.1/payload.schema.json'), ''),
}
const commit = process.argv[3] ?? 'unknown'
process.stdout.write(`/**
 * GENERATED by scripts/bundle-vetting-schemas.mjs — do not edit by hand. The
 * published JSON Schemas Keyring checks vetting documents against, bundled
 * self-contained from trust-tasks-tf at ${commit}:
 *
 * - \`vettingSessionPayload\` — vetting/session/0.1 payload.schema.json
 * - \`vettingCard\` — vetting/_shared/0.1/vetting-card.schema.json#/$defs/VettingCard
 *   (what vta-sdk \`vetting::card::parse_card\` validates, card.rs:203-207)
 * - \`vettingRequirements\` — vtc/join-requests/manifest/0.2 #/$defs/VettingRequirements
 *   (vta-sdk \`protocols::vetting::read_requirements\`, vetting.rs:485)
 * - \`vetterProfilePayload\` — vtc/vetting/vetters/profile/0.1 payload.schema.json
 *
 * These are the schemas vta-sdk validates against (\`against_own_schema\`,
 * \`against_definition\`, protocols/vetting.rs:406-431). What JSON Schema
 * cannot say is in vettingShape.ts.
 *
 * @module trust-tasks/module/vettingSchemas
 */

/* eslint-disable */
export const VETTING_SCHEMAS: Record<
  'vettingSessionPayload' | 'vettingCard' | 'vettingRequirements' | 'vetterProfilePayload',
  Record<string, unknown>
> = ${JSON.stringify(out, null, 2)}
`)
